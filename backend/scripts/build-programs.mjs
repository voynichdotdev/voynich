import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { spawn, spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const target = path.join(root, 'target')
const artifacts = path.join(root, 'programs/artifacts')
const names = ['voynich', 'attest', 'cpi-caller', 'bounty']
const sdkNames = ['voynich', 'attest', 'bounty']
// The SBF binaries are built as SBPF v0 (npm run build:sbf),
// which writes programs/artifacts/<name>.so. This script builds the IDLs on the host and generates
// the TypeScript IDL modules; it never installs or switches a Solana toolchain.
const env = { ...process.env, CARGO_TARGET_DIR: target }
const versioned = spawnSync('anchor-0.31.1', ['--version'], { encoding: 'utf8', windowsHide: true })
const anchor = versioned.error?.code === 'ENOENT' ? 'anchor' : 'anchor-0.31.1'
const version = spawnSync(anchor, ['--version'], { encoding: 'utf8', windowsHide: true })
if (version.status !== 0 || version.stdout.trim() !== 'anchor-cli 0.31.1') throw new Error('The program build requires Anchor CLI 0.31.1.')

mkdirSync(path.join(target, 'deploy'), { recursive: true })
mkdirSync(path.join(target, 'idl'), { recursive: true })
mkdirSync(path.join(target, 'types'), { recursive: true })
mkdirSync(artifacts, { recursive: true })
for (const name of names) {
  const key = path.join(root, 'keys', `${name}-keypair.json`)
  if (!existsSync(key)) throw new Error(`Missing keys/${name}-keypair.json. Create it once with solana-keygen; never regenerate an existing program key.`)
  const publicKey = spawnSync('solana-keygen', ['pubkey', key], { encoding: 'utf8', windowsHide: true })
  const source = readFileSync(path.join(root, 'programs', name, 'src/lib.rs'), 'utf8')
  if (publicKey.status !== 0 || source.match(/declare_id!\("([^"]+)"\)/)?.[1] !== publicKey.stdout.trim()) throw new Error(`${name}: canonical keypair and declared program address differ.`)
  copyFileSync(key, path.join(target, 'deploy', `${name}-keypair.json`))
}

// Build and IDL flags stay separate: SBF flags are not valid for Anchor's host IDL build.
// No deploy, validator, or program integration tests run here.
async function run(args) { await new Promise((resolve, reject) => {
  const child = spawn(anchor, args, { cwd: root, env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  let stackFailure = false
  let tail = ''
  function output(chunk, destination) {
    destination.write(chunk)
    const text = tail + chunk.toString()
    if (/Stack offset .*exceeded|Stack frame size .*exceeded|max stack frame size/i.test(text)) stackFailure = true
    tail = text.slice(-4096)
  }
  child.stdout.on('data', chunk => output(chunk, process.stdout))
  child.stderr.on('data', chunk => output(chunk, process.stderr))
  child.once('error', reject)
  child.once('exit', code => code === 0 && !stackFailure ? resolve() : reject(new Error(stackFailure ? 'SBF stack overflow diagnostic: refusing to publish artifacts.' : `anchor build exited with ${code}.`)))
}) }
for (const name of names) await run(['idl', 'build', '-p', name, '-o', path.join(target, 'idl', `${name}.json`), '-t', path.join(target, 'types', `${name}.ts`)])

mkdirSync(artifacts, { recursive: true })
mkdirSync(path.join(root, 'sdk/src/generated'), { recursive: true })
mkdirSync(path.join(root, 'src/generated'), { recursive: true })
for (const name of names) {
  const elf = readFileSync(path.join(artifacts, `${name}.so`))
  if (elf.readUInt32LE(48) !== 0) throw new Error(`${name}: expected an SBPF v0 ELF; run npm run build:sbf.`)
  const idlText = readFileSync(path.join(target, 'idl', `${name}.json`), 'utf8')
  const idl = JSON.parse(idlText)
  const source = readFileSync(path.join(root, 'programs', name, 'src/lib.rs'), 'utf8')
  if (source.match(/declare_id!\("([^"]+)"\)/)?.[1] !== idl.address) throw new Error(`${name}: source and IDL program addresses differ.`)
  copyFileSync(path.join(target, 'idl', `${name}.json`), path.join(artifacts, `${name}.json`))
  if (!sdkNames.includes(name)) continue
  const typeName = name[0].toUpperCase() + name.slice(1)
  const typeSource = readFileSync(path.join(target, 'types', `${name}.ts`), 'utf8')
  writeFileSync(path.join(root, 'sdk/src/generated', `${name}.ts`), `${typeSource}\n// Generated by npm run build:programs. Anchor converts the runtime IDL names to camelCase.\nexport const IDL: ${typeName} = ${JSON.stringify(idl, null, 2)} as unknown as ${typeName}\n`)
  writeFileSync(path.join(root, 'src/generated', `${name}.ts`), `// Generated by npm run build:programs.\nexport { IDL, type ${typeName} } from 'voynich/idl/${name}'\n`)
}
// Compile only the generated modules, leaving the fixture server's crypto module untouched.
const typescript = spawnSync(process.execPath, ['node_modules/typescript/bin/tsc', '--target', 'ES2022', '--module', 'NodeNext', '--moduleResolution', 'NodeNext', '--strict', '--skipLibCheck', '--declaration', '--outDir', 'sdk/dist/generated', ...sdkNames.map(name => `sdk/src/generated/${name}.ts`)], { cwd: root, stdio: 'inherit', windowsHide: true })
if (typescript.status !== 0) process.exit(typescript.status ?? 1)
console.log('IDLs and generated TypeScript IDL modules are ready.')
